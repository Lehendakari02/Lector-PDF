"""Create the Windows program with PyInstaller.

Usage (from the repository root):
    python packaging/build.py [--label TEXT] [--onefile]

Result: ``dist/Lector-PDF/`` (a folder with ``Lector-PDF.exe`` inside), or the
single file ``dist/onefile/Lector-PDF.exe`` with ``--onefile``.

The project ships the folder. ``--onefile`` is kept only to repeat the
comparison: measured in task 0.2, the single file took 2.7 s to open every
time (it unpacks itself on each start) against under 1 s for the folder.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD_INFO = ROOT / "app" / "_build_info.py"
PROGRAM_NAME = "Lector-PDF"

# Parts of Qt and Python the program does not use. Leaving them out makes the
# download smaller and the program quicker to start.
EXCLUDED_MODULES = [
    "PySide6.QtNetwork",
    "PySide6.QtQml",
    "PySide6.QtQuick",
    "PySide6.QtOpenGL",
    "PySide6.QtDBus",
    # Machine-learning layout tools that come with PyMuPDF 2 (see pyproject.toml).
    "pymupdf.layout",
    "pymupdf4llm",
    "onnxruntime",
    "numpy",
    "networkx",
    "tkinter",
    "unittest",
    "pydoc",
]


# Files the program reads while running; they keep the same path inside it.
DATA_FOLDERS = [
    "app/recursos/tessdata",  # Spanish language file for text recognition
    "app/recursos/interfaz",  # small pictures of the interface
]
ICON = ROOT / "packaging" / "lector-pdf.ico"  # drawn by packaging/make_images.py


def write_build_info(label: str) -> None:
    BUILD_INFO.write_text(
        f'"""Generated by packaging/build.py. Do not edit."""\n\nBUILD_LABEL = {label!r}\n',
        encoding="utf-8",
    )


# Model files PyInstaller copies along with PyMuPDF although nothing can use them.
UNUSED_FOLDERS = ["_internal/pymupdf/layout", "_internal/pymupdf/mupdf-devel"]


def remove_unused_folders() -> None:
    for folder in UNUSED_FOLDERS:
        shutil.rmtree(ROOT / "dist" / PROGRAM_NAME / folder, ignore_errors=True)


# The licence of the program and of everything inside it goes in plain view,
# next to the ``.exe`` (see app/core/about.py and the "Acerca de" window).
LICENCE_FOLDER = "licencias"
OWN_LICENCE_NAME = "AGPL-3.0.txt"
DIRECT_DEPENDENCIES = ["PySide6_Essentials", "PyMuPDF", "pyHanko"]
# Installed with PyMuPDF but left out of the program (EXCLUDED_MODULES).
NOT_SHIPPED = {"pymupdf-layout", "pymupdf4llm", "onnxruntime", "numpy", "networkx"}
LICENCE_WORDS = ("licen", "copying", "notice", "authors")


def _plain_name(requirement: str) -> str:
    return re.split(r"[\s;<>=!~\[(]", requirement.strip(), maxsplit=1)[0].lower().replace("_", "-")


def shipped_packages() -> list[metadata.Distribution]:
    """The direct dependencies and everything they need, except what is left out."""
    found: dict[str, metadata.Distribution] = {}
    waiting = [_plain_name(name) for name in DIRECT_DEPENDENCIES]
    while waiting:
        name = waiting.pop()
        if name in found or name in NOT_SHIPPED:
            continue
        try:
            package = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue  # only needed on another system, or for an optional extra
        found[name] = package
        for requirement in package.requires or []:
            if "extra ==" not in requirement:
                waiting.append(_plain_name(requirement))
    return [found[name] for name in sorted(found)]


def copy_licences(target: Path) -> int:
    """Put every licence text in ``target``. Returns how many packages gave one."""
    shutil.rmtree(target, ignore_errors=True)
    shutil.copytree(ROOT / "app" / "recursos" / "licencias", target)
    shutil.copyfile(ROOT / "LICENSE", target / OWN_LICENCE_NAME)
    with_text = 0
    for package in shipped_packages():
        texts = [
            file
            for file in package.files or []
            if ".dist-info" in str(file) and any(w in file.name.lower() for w in LICENCE_WORDS)
        ]
        folder = target / "paquetes" / f"{package.name}-{package.version}"
        for file in texts:
            folder.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(file.locate(), folder / file.name)
        with_text += bool(texts)
    return with_text


def run_pyinstaller(onefile: bool) -> None:
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--windowed",
        "--icon",
        str(ICON),
        "--name",
        PROGRAM_NAME,
        "--paths",
        str(ROOT),
        "--workpath",
        str(ROOT / "build" / ("onefile" if onefile else "onedir")),
        "--specpath",
        str(ROOT / "build"),
    ]
    for module in EXCLUDED_MODULES:
        command += ["--exclude-module", module]
    for folder in DATA_FOLDERS:
        command += ["--add-data", f"{ROOT / folder}{os.pathsep}{folder}"]
    if onefile:
        command += ["--onefile", "--distpath", str(ROOT / "dist" / "onefile")]
    else:
        command += ["--onedir", "--distpath", str(ROOT / "dist")]
    command.append(str(ROOT / "packaging" / "launcher.py"))
    subprocess.run(command, check=True, cwd=ROOT)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--label", default="", help="text shown in the window for this build")
    parser.add_argument("--onefile", action="store_true", help="build a single .exe file")
    options = parser.parse_args()

    write_build_info(options.label)
    try:
        run_pyinstaller(options.onefile)
        if not options.onefile:
            remove_unused_folders()
            copy_licences(ROOT / "dist" / PROGRAM_NAME / LICENCE_FOLDER)
    finally:
        # Never leave the generated file behind in a working copy.
        BUILD_INFO.unlink(missing_ok=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
